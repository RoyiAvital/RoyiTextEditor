/// `prefix`, then `block` with `$N` = 0, 1, ... while the total stays within `size`.
fn repeat(prefix: &str, block: &str, size: usize) -> Vec<u8> {
    let mut out = prefix.as_bytes().to_vec();
    for n in 0.. {
        let next = block.replace("$N", &n.to_string());
        if out.len() + next.len() > size {
            break;
        }
        out.extend_from_slice(next.as_bytes());
    }
    out
}

fn code(block: &str, size: usize) -> Vec<u8> {
    repeat("", block, size)
}

/// `block` repeated (`$N` = 0, 1, ...) while the text stays within `count` lines.
fn lines(block: &str, count: usize) -> Vec<u8> {
    let per_block = block.matches('\n').count();
    let mut out = Vec::new();
    for n in 0..count / per_block {
        out.extend_from_slice(block.replace("$N", &n.to_string()).as_bytes());
    }
    out
}

fn markdown(size: usize) -> Vec<u8> {
    repeat(MD_FRONT, MD, size)
}

fn csv(size: usize) -> Vec<u8> {
    repeat(CSV_HEADER, CSV_ROW, size)
}

/// One JSON array within `size`; `indent` and `separator` choose the pretty
/// (one item per line) or minified (single line) form.
fn json(size: usize, indent: &str, separator: &str) -> Vec<u8> {
    let compact = indent.is_empty();
    let item = |n: usize| {
        let text = JSON_ITEM.replace("$N", &n.to_string());
        if compact {
            text.replace(": ", ":").replace(", ", ",")
        } else {
            format!("{indent}{text}")
        }
    };
    let (open, close) = if compact {
        ("[", "]")
    } else {
        ("[\n", "\n]\n")
    };
    let mut out = open.as_bytes().to_vec();
    for n in 0.. {
        let next = item(n);
        let extra = if n > 0 { separator.len() } else { 0 };
        if out.len() + extra + next.len() + close.len() > size {
            break;
        }
        if n > 0 {
            out.extend_from_slice(separator.as_bytes());
        }
        out.extend_from_slice(next.as_bytes());
    }
    out.extend_from_slice(close.as_bytes());
    out
}

