fn file_hash(path: &Path) -> Option<u64> {
    let bytes = fs::read(path).ok()?;
    let mut hasher = Xxh3::new();
    hasher.update(&bytes);
    Some(hasher.digest())
}

/// Generates missing or changed fixtures and verifies all hashes.
fn prepare_fixtures(print_hashes: bool) -> Result<(), String> {
    let dir = fixture_dir();
    fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    let mut changed = Vec::new();
    for fixture in FIXTURES {
        let path = dir.join(fixture.name);
        if !print_hashes && file_hash(&path) == Some(fixture.hash) {
            continue;
        }
        let bytes = (fixture.generate)();
        let hash = xxh3_64(&bytes);
        if print_hashes {
            println!(
                "{:<12} {:>10} bytes  hash: 0x{hash:016x}",
                fixture.name,
                bytes.len()
            );
        } else if hash != fixture.hash {
            changed.push(format!(
                "{} (0x{hash:016x}, recorded 0x{:016x})",
                fixture.name, fixture.hash
            ));
            continue;
        }
        let mut file = fs::File::create(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        file.write_all(&bytes)
            .map_err(|e| format!("{}: {e}", path.display()))?;
    }
    if changed.is_empty() {
        Ok(())
    } else {
        Err(format!(
            "fixtures differ from benchmark v{VERSION}: {}. Record the new hashes only while v{VERSION} is unpublished; otherwise create a new benchmark version.",
            changed.join(", ")
        ))
    }
}

struct Samples {
    first_paint: Vec<f64>,
    first_frame: Vec<f64>,
    loaded: Vec<f64>,
    peak: Vec<f64>,
    /// Wall time of the whole test, warm-up included.
    elapsed: Duration,
}

fn run_load(exe: &Path, t: &LoadTest) -> Result<Samples, String> {
    let path = fixture_dir().join(t.fixture);
    let mut samples = Samples {
        first_paint: Vec::new(),
        first_frame: Vec::new(),
        loaded: Vec::new(),
        peak: Vec::new(),
        elapsed: Duration::ZERO,
    };
    let start = Instant::now();
    // One warm-up run (file cache, executable image), not counted.
    for run in 0..=t.runs {
        let mut command = Command::new(exe);
        command.args(["--trace-startup", "--exit-after-load"]);
        if t.read_only {
            command.arg("--read-only");
        }
        if let Some(id) = t.syntax {
            command.args(["--syntax", id]);
        }
        command.arg(&path);
        let trace = run_traced(&mut command, Duration::from_secs(10))
            .and_then(|out| parse_trace(&out))
            .map_err(|e| format!("{}: {e}", t.id))?;
        if run == 0 {
            continue;
        }
        let value = |key: &str| {
            trace
                .get(key)
                .copied()
                .ok_or_else(|| format!("{}: no {key} in the trace", t.id))
        };
        samples.first_paint.push(value("first_paint")?);
        samples.first_frame.push(value("first_frame")?);
        samples.loaded.push(value("file_read")?);
        samples.peak.push(value("peak_private_mib")?);
    }
    let elapsed = start.elapsed();
    if elapsed > t.cap {
        return Err(format!(
            "{} took {:.2} s, over its {} s cap",
            t.id,
            elapsed.as_secs_f64(),
            t.cap.as_secs()
        ));
    }
    samples.elapsed = elapsed;
    Ok(samples)
}

struct InputSamples {
    /// Milliseconds from handling the first key to its presented frame.
    key_to_frame: Vec<f64>,
    elapsed: Duration,
}

fn run_input(exe: &Path, t: &InputTest) -> Result<InputSamples, String> {
    let start = Instant::now();
    let runs = (t.runs + 1).to_string();
    let mut command = Command::new(exe);
    command
        .args(["--bench-keys", t.keys, "--bench-runs", &runs])
        .arg(fixture_dir().join(t.fixture));
    let out =
        run_traced(&mut command, Duration::from_secs(10)).map_err(|e| format!("{}: {e}", t.id))?;
    let mut first = Vec::new();
    for line in out.lines().map(str::trim).filter(|l| !l.is_empty()) {
        let (step, ms) = line
            .strip_prefix("bench.")
            .and_then(|l| l.split_once("_ms="))
            .ok_or_else(|| format!("{}: unexpected output line {line:?}", t.id))?;
        let ms = ms
            .parse::<f64>()
            .ok()
            .filter(|ms| ms.is_finite() && *ms >= 0.0)
            .ok_or_else(|| format!("{}: invalid value in {line:?}", t.id))?;
        if step == "0" {
            first.push(ms);
        }
    }
    if first.len() != t.runs + 1 {
        return Err(format!(
            "{}: {} of {} repetitions reported",
            t.id,
            first.len(),
            t.runs + 1
        ));
    }
    first.remove(0);
    let elapsed = start.elapsed();
    if elapsed > t.cap {
        return Err(format!(
            "{} took {:.2} s, over its {} s cap",
            t.id,
            elapsed.as_secs_f64(),
            t.cap.as_secs()
        ));
    }
    Ok(InputSamples {
        key_to_frame: first,
        elapsed,
    })
}

fn command_output(program: &str, args: &[&str]) -> String {
    Command::new(program)
        .args(args)
        .current_dir(root())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .unwrap_or_else(|| "unknown".to_owned())
}

pub fn bench_perf(args: &[String]) -> ExitCode {
    let print_hashes = args.iter().any(|a| a == "--print-hashes");
    let short = args.iter().any(|a| a == "--short");
    if !print_hashes && !build_release() {
        eprintln!("release build failed");
        return ExitCode::FAILURE;
    }
    let started = Instant::now();
    if let Err(e) = prepare_fixtures(print_hashes) {
        eprintln!("{e}");
        return ExitCode::FAILURE;
    }
    if print_hashes {
        return ExitCode::SUCCESS;
    }
    let fixtures = started.elapsed();
    if fixtures > FIXTURE_CAP {
        eprintln!(
            "fixture preparation took {:.2} s, over its {} s cap",
            fixtures.as_secs_f64(),
            FIXTURE_CAP.as_secs()
        );
        return ExitCode::FAILURE;
    }

    let info = match crate::app_info() {
        Ok(info) => info,
        Err(e) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    println!(
        "{} {}, Performance Benchmark v{VERSION}{}, {}, {}",
        info.name,
        info.version,
        if short { " (short)" } else { "" },
        command_output("rustc", &["--version"]),
        std::env::var("PROCESSOR_IDENTIFIER").unwrap_or_default(),
    );
    println!();
    let exe = release_exe();
    let mut results = Vec::new();
    for t in LOAD_TESTS.iter().filter(|t| !short || short_includes(t.id)) {
        match run_load(&exe, t) {
            Ok(samples) => results.push((t, samples)),
            Err(e) => {
                eprintln!("{e}");
                return ExitCode::FAILURE;
            }
        }
    }
    let mut inputs = Vec::new();
    for t in INPUT_TESTS
        .iter()
        .filter(|t| !short || short_includes(t.id))
    {
        match run_input(&exe, t) {
            Ok(samples) => inputs.push((t, samples)),
            Err(e) => {
                eprintln!("{e}");
                return ExitCode::FAILURE;
            }
        }
    }
    let total = started.elapsed();
    if short {
        print_short(&results, &inputs);
        println!();
        println!("Medians. Total {:.1} s.", total.as_secs_f64());
        return ExitCode::SUCCESS;
    }
    println!(
        "| ID  | Test                     | First paint [ms] | First frame [ms] | File read [ms] | Peak private [MiB] | Time [s] |"
    );
    println!(
        "| --- | ------------------------ | ---------------- | ---------------- | -------------- | ------------------ | -------- |"
    );
    for (t, samples) in &results {
        let loaded = if t.loaded {
            format!("{:.1}", median(&samples.loaded))
        } else {
            "-".to_owned()
        };
        println!(
            "| {:<3} | {:<24} | {:>16.1} | {:>16.1} | {:>14} | {:>18.1} | {:>8.2} |",
            t.id,
            t.label,
            median(&samples.first_paint),
            median(&samples.first_frame),
            loaded,
            median(&samples.peak),
            samples.elapsed.as_secs_f64()
        );
    }
    println!();
    println!("| ID  | Test                     | Key to frame [ms] | p95 [ms] | Time [s] |");
    println!("| --- | ------------------------ | ----------------- | -------- | -------- |");
    for (t, samples) in &inputs {
        let mut sorted = samples.key_to_frame.clone();
        sorted.sort_by(f64::total_cmp);
        println!(
            "| {:<3} | {:<24} | {:>17.2} | {:>8.2} | {:>8.2} |",
            t.id,
            t.label,
            median(&samples.key_to_frame),
            percentile(&sorted, 0.95),
            samples.elapsed.as_secs_f64()
        );
    }
    println!();
    println!(
        "Medians. Fixtures {:.2} s; total {:.1} s (cap {} s, {} s reserved for interaction tests). Not run (need the scripted input mode): {PENDING}.",
        fixtures.as_secs_f64(),
        total.as_secs_f64(),
        TOTAL_CAP.as_secs(),
        PENDING_CAPS.as_secs()
    );
    if total + PENDING_CAPS > TOTAL_CAP {
        eprintln!("the run exceeded its {} s cap", TOTAL_CAP.as_secs());
        return ExitCode::FAILURE;
    }
    ExitCode::SUCCESS
}

fn print_short(results: &[(&LoadTest, Samples)], inputs: &[(&InputTest, InputSamples)]) {
    let rows: Vec<[String; 4]> = SHORT
        .iter()
        .map(|r| {
            let samples = results.iter().find(|(t, _)| t.id == r.id).map(|(_, s)| s);
            let input = inputs.iter().find(|(t, _)| t.id == r.id).map(|(_, s)| s);
            let (measure, result) = match (&r.measure, samples) {
                (Measure::KeyToFrame, _) => (
                    "Key to frame".to_owned(),
                    input.map_or_else(String::new, |s| {
                        format!("{:.2} ms", median(&s.key_to_frame))
                    }),
                ),
                (Measure::FirstPaint, Some(s)) => (
                    "Time to first frame".to_owned(),
                    format!("{:.1} ms", median(&s.first_paint)),
                ),
                (Measure::FileRead, Some(s)) => (
                    "Time to load fully".to_owned(),
                    format!("{:.1} ms", median(&s.loaded)),
                ),
                (Measure::Peak, Some(s)) => (
                    "Peak memory".to_owned(),
                    format!("{:.1} MiB", median(&s.peak)),
                ),
                (Measure::NotMeasured(m), _) => ((*m).to_owned(), "Not measured yet".to_owned()),
                (Measure::NotImplemented(m), _) => {
                    ((*m).to_owned(), "Feature not implemented yet".to_owned())
                }
                (_, None) => unreachable!("short rows of load tests are run"),
            };
            [
                r.question.to_owned(),
                r.scenario.to_owned(),
                measure,
                result,
            ]
        })
        .collect();
    print!(
        "{}",
        markdown_table(["Question", "Scenario", "Measure", "Result"], &rows)
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generators_are_deterministic_and_sized() {
        assert_eq!(code(PY, 64 * KIB), code(PY, 64 * KIB));
        assert!(code(C, 64 * KIB).len() <= 64 * KIB);
        let line = json(64 * KIB, "", ",");
        assert!(line.len() <= 64 * KIB && !line.contains(&b'\n'));
        assert!(std::str::from_utf8(&json(64 * KIB, "  ", ",\n")).is_ok());
        assert_eq!(tile(b"abc", 7), b"abcabca");
    }

    #[test]
    fn notebook_is_valid_json_with_images() {
        let bytes = notebook(64 * KIB);
        assert!(bytes.len() <= 64 * KIB);
        let nb: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        let cells = nb["cells"].as_array().unwrap();
        assert!(cells.len() >= 4);
        assert_eq!(cells[0]["cell_type"], "markdown");
        let png = nb["cells"][1]["outputs"][1]["data"]["image/png"]
            .as_str()
            .unwrap();
        assert!(png.starts_with("iVBORw0KGgo"));
        assert_eq!(base64(b"Man"), "TWFu");
        assert_eq!(base64(b"Ma"), "TWE=");
        assert_eq!(base64(b"M"), "TQ==");
        assert_eq!(crc32(b"IEND"), 0xAE42_6082);
    }

    #[test]
    fn short_rows_measure_existing_tests() {
        for row in SHORT {
            let test = LOAD_TESTS.iter().find(|t| t.id == row.id);
            let input = INPUT_TESTS.iter().find(|t| t.id == row.id);
            match row.measure {
                Measure::NotMeasured(_) | Measure::NotImplemented(_) => {
                    assert!(
                        test.is_none() && input.is_none(),
                        "{} is implemented",
                        row.id
                    )
                }
                Measure::FileRead => assert!(test.is_some_and(|t| t.loaded), "{}", row.id),
                Measure::KeyToFrame => assert!(input.is_some(), "{} is not an input test", row.id),
                _ => assert!(test.is_some(), "{} is not a load test", row.id),
            }
        }
        for t in INPUT_TESTS {
            assert!(t.keys.split(',').all(|k| !k.trim().is_empty()), "{}", t.id);
        }
        let table = markdown_table(
            ["A", "Bb", "C"],
            &[["long cell".into(), "x".into(), "µs".into()]],
        );
        assert_eq!(
            table,
            "| A         | Bb | C  |\n| --------- | -- | -- |\n| long cell | x  | µs |\n"
        );
    }
}
