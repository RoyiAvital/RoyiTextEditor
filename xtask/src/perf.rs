/// `chunk` repeated to exactly `size` bytes (fast for large fixtures).
fn tile(chunk: &[u8], size: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(size);
    while out.len() < size {
        let take = chunk.len().min(size - out.len());
        out.extend_from_slice(&chunk[..take]);
    }
    out
}

